    # ------------------------------------------------------------------
    # Config accessors (bash variables are always strings; these coerce)
    # ------------------------------------------------------------------
    def _cfg_lookup(self, name):
        """Like bash's implicit variable lookup: config-set values win, but a
        variable the config file never touched still falls back to whatever
        was inherited from the calling shell's environment (e.g. CRASH_CHECK,
        which pstress-run.sh reads without ever assigning it itself)."""
        if name in self.cfg:
            return self.cfg[name]
        return os.environ.get(name)

    def s(self, name, default=""):
        v = self._cfg_lookup(name)
        return v if v not in (None, "") else default

    def i(self, name, default=0):
        v = self._cfg_lookup(name)
        if v in (None, ""):
            return default
        try:
            return int(v)
        except ValueError:
            return default

    def set_cfg(self, name, value):
        self.cfg[name] = "" if value is None else str(value)

    def b(self, name, default=False):
        v = self._cfg_lookup(name)
        if v in (None, ""):
            return default
        return v == "1"

    # ------------------------------------------------------------------
    # Output
    # ------------------------------------------------------------------
    def echoit(self, msg):
        line = f"[{time.strftime('%H:%M:%S')}] [{self.saved}] {msg}"
        print(line)
        if self.workdiractive:
            append_text(Path(self.s("WORKDIR")) / "pstress-run.log", line + "\n")

    # ------------------------------------------------------------------
    # kill_server(): send SIG to PID and wait for it if it is a direct child
    # ------------------------------------------------------------------
    def kill_server(self, sig, pid, proc=None):
        if not pid:
            return
        pid = int(pid)
        try:
            os.kill(pid, sig)
        except (ProcessLookupError, PermissionError, ValueError, TypeError):
            self._tracked_procs.pop(pid, None)
            return

        # `kill_server 9 $PID && wait $PID` in pstress-run.sh only really
        # *blocks* when $PID is a genuine job-control child of the running
        # shell (e.g. the mysqld it just backgrounded with `&`); for a PID
        # discovered via a fresh `ps -ef` scan (someone else's process, or
        # this shell's own but already exited) `wait` returns immediately.
        # subprocess.Popen.wait() only works for our own tracked children
        # too, so mirror that split rather than always doing a best-effort
        # poll: a tracked child gets a real, confirmed wait (matching bash's
        # guarantee that the port is released before the caller continues);
        # anything else gets the best-effort existence poll.
        if proc is None:
            proc = self._tracked_procs.get(pid)
        if proc is not None:
            try:
                proc.wait(timeout=60)
            except Exception:
                pass
            self._tracked_procs.pop(pid, None)
            return

        # Best-effort: PID may not be our child, so just poll briefly.
        for _ in range(60):
            try:
                os.kill(pid, 0)
            except (ProcessLookupError, ValueError, TypeError):
                return
            time.sleep(0.5)

    # ------------------------------------------------------------------
    # ASan/Sanitizer detection
    # ------------------------------------------------------------------
    def check_asan_error(self):
        logs = glob.glob(f"{self.s('RUNDIR')}/{self.trial}/asan.log.*")
        if not logs:
            return False
        return grep_count(r"==[0-9]+==ERROR:", *logs, ignore_case=False) > 0

    def get_asan_error_lines(self):
        logs = glob.glob(f"{self.s('RUNDIR')}/{self.trial}/asan.log.*")
        lines = []
        rx = re.compile(r"==[0-9]+==ERROR:")
        for f in logs:
            try:
                with open(f, errors="replace") as fh:
                    for n, l in enumerate(fh, 1):
                        if rx.search(l):
                            lines.append(f"{f}:{n}:{l.rstrip()}")
            except OSError:
                continue
        return "\n".join(lines)

