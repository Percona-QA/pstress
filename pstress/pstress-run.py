    # ------------------------------------------------------------------
    # Restart helper (used by execute_sql_files kill/restart mode)
    # ------------------------------------------------------------------
    def kill_and_restart_server(self):
        rundir = self.s("RUNDIR")
        basedir = self.s("BASEDIR")
        if self.pxc == 0 and self.grp_rpl == 0:
            for pid in pids_matching(f"socket={self.socket}", rundir):
                self.echoit(f"Killing server (pid: {pid}) for restart...")
                self.kill_server(9, pid)

            restart_cmd = getattr(self, "server_restart_cmd", None)
            if not restart_cmd:
                self.echoit("ERROR: SERVER_RESTART_CMD is not set. Cannot restart server.")
                self.echoit("ERROR: Check if the server setup was not done properly.")
                return False

            self.echoit("Restarting server...")
            self.mpid = self._spawn(restart_cmd, out_path=f"{rundir}/{self.trial}/log/master.err")

            self.echoit(f"Waiting for server (pid: {self.mpid}) to restart...")
            for x in range(0, self.mysqld_start_timeout + 1):
                time.sleep(1)
                if sh_status(f"{basedir}/bin/mysqladmin -uroot -S{shlex.quote(self.socket)} ping > /dev/null 2>&1") == 0:
                    self.echoit("Server restarted successfully")
                    return True
                if x == self.mysqld_start_timeout:
                    self.echoit(f"ERR: Server failed to restart after {self.mysqld_start_timeout} seconds")
                    return False

        if self.pxc == 1 or self.grp_rpl == 1:
            for pid in pids_matching("n", ".cnf", rundir):
                self.kill_server(9, pid)
            time.sleep(2)
            if self.pxc == 1:
                sed_replace(f"{rundir}/{self.trial}/node1/grastate.dat", r"safe_to_bootstrap:.*$", "safe_to_bootstrap: 1")
                self.pxc_startup()
            elif self.grp_rpl == 1:
                # NOTE: pstress-run.sh calls an undefined `grp_rpl_startup` here (a
                # latent bug/typo -- the only startup function defined is
                # `gr_startup`). This port calls the function that actually exists.
                self.gr_startup()
        return True

    # ------------------------------------------------------------------
    # SQL file execution mode
    # ------------------------------------------------------------------
    def execute_sql_files(self):
        step_dir = self.s("SQL_FILES_STEP_DIR")
        step_num = self.s("SQL_FILES_STEP_NUM")
        self.echoit(f"Executing SQL files for step {step_num} from {step_dir}")
        basedir = self.s("BASEDIR")
        socket = self.socket1 if (self.pxc == 1 or self.grp_rpl == 1) else self.socket

        def execute_queries_from_file(path):
            with open(path) as fh:
                proc = subprocess.run([f"{basedir}/bin/mysql", "-uroot", "-S", socket, "-f"], stdin=fh)
            if proc.returncode != 0:
                self.echoit(f"ERROR: Failed to execute {path} file")
                return False
            return True

        def set_global_variable(assignment):
            proc = subprocess.run([f"{basedir}/bin/mysql", "-uroot", "-S", socket, "-e", f"set global {assignment}"])
            if proc.returncode != 0:
                self.echoit(f"ERROR setting global variable {assignment}")
                return False
            return True

        ts_file = f"{step_dir}/ts{step_num}.sql"
        if os.path.isfile(ts_file):
            self.echoit(f"Executing {ts_file} file")
            if not execute_queries_from_file(ts_file):
                return False

        if self.pxc == 1:
            if not set_global_variable("pxc_strict_mode=DISABLED"):
                return False

        dump_file = f"{step_dir}/dump_pstress{step_num}.sql"
        if os.path.isfile(dump_file):
            self.echoit(f"Executing {dump_file} file")
            if not execute_queries_from_file(dump_file):
                return False
        else:
            self.echoit(f"Warning: Dump file dump_pstress{step_num}.sql not found in {step_dir}")

        if self.pxc == 1:
            if not set_global_variable("pxc_strict_mode=DISABLED"):
                return False

        workaround_file = f"{step_dir}/workaround.sql"
        if os.path.isfile(workaround_file):
            self.echoit(f"Executing {workaround_file} file")
            if not execute_queries_from_file(workaround_file):
                return False

        self.echoit("Executing step SQL files (reduced_*)")
        number_of_times = self.i("SQL_FILES_NUMBER_OF_TIMES", 1)
        if number_of_times == 0:
            self.echoit("Skipping executing the step sqls (number_of_times=0)")
            return True

        single_threaded = self.i("SQL_FILES_SINGLE_THREADED") == 1
        sql_timeout = self.i("SQL_FILES_TIMEOUT", 60)
        kill_and_restart = self.i("SQL_FILES_KILL_AND_RESTART_SERVER") == 1

        for loop_i in range(1, number_of_times + 1):
            reduced_files = sorted(glob.glob(f"{step_dir}/reduced_*"))
            procs = []
            for sql_file in reduced_files:
                if not os.path.isfile(sql_file):
                    continue
                self.echoit(f"Executing SQL file: {os.path.basename(sql_file)}")
                fh = open(sql_file)
                proc = subprocess.Popen(
                    [f"{basedir}/bin/mysql", "-uroot", "-S", socket, "-f"],
                    stdin=fh, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                )
                procs.append(proc)

                if single_threaded:
                    self.echoit(f"Started SQL file execution process: {proc.pid}")
                    time.sleep(sql_timeout)
                    if kill_and_restart:
                        self.echoit("Killing and restarting server (single-threaded mode)")
                        self.kill_and_restart_server()
                    if proc.poll() is None:
                        proc.terminate()
                        self.echoit(f"Killed SQL file execution process {proc.pid}")
                fh.close()

            if not procs:
                self.echoit(f"No reduce_d* SQL files found in {step_dir}")
                break

            if not single_threaded:
                self.echoit(f"Started {len(procs)} SQL file execution processes: {' '.join(str(p.pid) for p in procs)}")

                def timeout_watcher():
                    time.sleep(sql_timeout)
                    if kill_and_restart:
                        self.echoit("Timeout reached. Killing and restarting server")
                        self.kill_and_restart_server()
                    self.echoit("Killing remaining SQL execution jobs...")
                    for p in procs:
                        if p.poll() is None:
                            p.terminate()
                            self.echoit(f"Killed SQL file execution process {p.pid}")

                import threading

                watcher = threading.Thread(target=timeout_watcher, daemon=True)
                watcher.start()

                for p in procs:
                    p.wait()

                if kill_and_restart:
                    watcher.join(timeout=1)
                # else: nothing to kill, watcher thread will exit on its own.

            self.echoit(f"Loop {loop_i} of {number_of_times} completed")

        self.echoit(f"SQL files execution completed for step {step_num}")
        return True

