    def pxc_startup(self, is_startup=""):
        basedir = self.s("BASEDIR")
        rundir = self.s("RUNDIR")
        workdir = self.s("WORKDIR")
        mysql_version = getattr(self, "mysql_version", "")
        addr = "127.0.0.1"
        rport = (random.randint(0, 32767) % 21 + 10) * 1000
        self.socket1 = f"{rundir}/{self.trial}/node1/node1_socket.sock"
        self.socket2 = f"{rundir}/{self.trial}/node2/node2_socket.sock"
        self.socket3 = f"{rundir}/{self.trial}/node3/node3_socket.sock"

        if check_for_version(mysql_version, "5.7.0"):
            mid = f"{self.mysqld_bin} --no-defaults --initialize-insecure --basedir={basedir}"
        else:
            mid = f"{self.mysqld_bin} --no-defaults --basedir={basedir}"

        if is_startup != "startup":
            write_text(
                f"{rundir}/{self.trial}/start_pxc_recovery",
                "echo '=== Starting PXC cluster for recovery...'\n"
                f"sed -i 's|safe_to_bootstrap:.*$|safe_to_bootstrap: 1|' {workdir}/{self.trial}/node1/grastate.dat\n",
            )

        # PXC_LADDRS in the shell script starts life as PXC_LADDRS="" (a plain
        # scalar) and is then grown with PXC_LADDRS+=("$LADDR1"). Bash's `+=`
        # on a variable that is not already an array keeps the prior scalar
        # value as index 0 and appends new elements from index 1 onward, so
        # the three loop iterations land at indices 1, 2, 3 (not 0, 1, 2) --
        # matching how pxc_startup() later reads ${PXC_LADDRS[1..3]}.
        pxc_laddrs = [""]
        datadir = None
        for i in range(1, 4):
            if is_startup == "startup":
                node = f"{workdir}/node{i}.template"
                if not check_for_version(mysql_version, "5.7.0"):
                    os.makedirs(node, exist_ok=True)
                datadir = workdir
            else:
                node = f"{rundir}/{self.trial}/node{i}"
                datadir = f"{rundir}/{self.trial}"

            os.makedirs(f"{datadir}/tmp{i}", exist_ok=True)
            rbase1 = rport + (100 * i)
            laddr1 = f"127.0.0.1:{rbase1 + 8}"
            pxc_laddrs.append(laddr1)

            ncnf = f"{datadir}/n{i}.cnf"
            shutil.copyfile(f"{basedir}/my.cnf", ncnf)
            sed_2i(ncnf, f"server-id=10{i}")
            sed_2i(ncnf, f"wsrep_node_incoming_address={addr}")
            sed_2i(ncnf, f"wsrep_node_address={addr}")
            sed_2i(ncnf, f"log-error={node}/node{i}.err")
            sed_2i(ncnf, f"port={rbase1}")
            sed_2i(ncnf, f"datadir={node}")

            if self.b_encryption_run() and is_startup != "startup":
                sed_2i(ncnf, "pxc_encrypt_cluster_traffic=ON")
                if check_for_version(mysql_version, "8.0.0"):
                    sed_2i(ncnf, "binlog_encryption=ON")
                if self.i("PLUGIN_KEYRING_FILE") == 1:
                    sed_2i(ncnf, "early-plugin-load=keyring_file.so")
                    if is_startup == "startup":
                        sed_2i(ncnf, f"keyring_file_data={datadir}/node{i}.template/keyring_storage/keyring")
                    else:
                        sed_2i(ncnf, f"keyring_file_data={datadir}/node{i}/keyring_storage/keyring")
                elif self.i("PLUGIN_KEYRING_VAULT") == 1:
                    sed_2i(ncnf, "early-plugin-load=keyring_vault.so")
                    sed_2i(ncnf, f"keyring_vault_config={workdir}/vault/keyring_vault_pxc{i}.cnf")

            if not self.b_encryption_run():
                sed_2i(ncnf, f'wsrep_provider_options="gmcast.listen_addr=tcp://{laddr1};{self.wsrep_provider_opt}"')
            else:
                sed_2i(
                    ncnf,
                    f'wsrep_provider_options="gmcast.listen_addr=tcp://{laddr1};{self.wsrep_provider_opt};'
                    f'socket.ssl_key={workdir}/cert/server-key.pem;socket.ssl_cert={workdir}/cert/server-cert.pem;'
                    f'socket.ssl_ca={workdir}/cert/ca.pem"',
                )
            sed_2i(ncnf, f"socket={node}/node{i}_socket.sock")
            sed_2i(ncnf, f"tmpdir={datadir}/tmp{i}")
            append_text(
                ncnf,
                f"ssl-ca = {workdir}/cert/ca.pem\n"
                f"ssl-cert = {workdir}/cert/server-cert.pem\n"
                f"ssl-key = {workdir}/cert/server-key.pem\n"
                "[client]\n"
                f"ssl-ca = {workdir}/cert/ca.pem\n"
                f"ssl-cert = {workdir}/cert/client-cert.pem\n"
                f"ssl-key = {workdir}/cert/client-key.pem\n"
                "[sst]\n"
                "encrypt = 4\n"
                f"ssl-ca = {workdir}/cert/ca.pem\n"
                f"ssl-cert = {workdir}/cert/server-cert.pem\n"
                f"ssl-key = {workdir}/cert/server-key.pem\n",
            )
            if is_startup == "startup":
                rc = sh_status(f"{mid} --datadir={shlex.quote(node)} > {shlex.quote(workdir)}/startup_node{i}.err 2>&1")
                if rc != 0:
                    sys.exit(1)

        if is_startup == "startup":
            os.makedirs(f"{workdir}/cert", exist_ok=True)
            sh(f"cp {workdir}/node1.template/*.pem {workdir}/cert/")

        gcomm = f"gcomm://{bash_index(pxc_laddrs, 1)},{bash_index(pxc_laddrs, 2)},{bash_index(pxc_laddrs, 3)}"
        sed_2i(f"{datadir}/n1.cnf", f"wsrep_cluster_address={gcomm}")
        sed_2i(f"{datadir}/n2.cnf", f"wsrep_cluster_address={gcomm}")
        sed_2i(f"{datadir}/n3.cnf", f"wsrep_cluster_address={gcomm}")

        rr_mode = self.i("RR_MODE")
        ps_extra = self.ps_extra
        pxc_extra = self.pxc_extra

        self.get_error_socket_file(1, is_startup == "startup")
        cmd = f"{self.mysqld_bin} --defaults-file={datadir}/n1.cnf {ps_extra} {pxc_extra} --wsrep-new-cluster > {shlex.quote(self.err_file)} 2>&1"
        self.mpid = self._spawn(("rr " + cmd) if rr_mode >= 1 else cmd)
        self.pxc_startup_status(1)

        self.get_error_socket_file(2, is_startup == "startup")
        cmd = f"{self.mysqld_bin} --defaults-file={datadir}/n2.cnf {ps_extra} {pxc_extra} > {shlex.quote(self.err_file)} 2>&1"
        self.mpid = self._spawn(("rr " + cmd) if rr_mode >= 1 else cmd)
        self.pxc_startup_status(2)

        self.get_error_socket_file(3, is_startup == "startup")
        cmd = f"{self.mysqld_bin} --defaults-file={datadir}/n3.cnf {ps_extra} {pxc_extra} > {shlex.quote(self.err_file)} 2>&1"
        self.mpid = self._spawn(("rr " + cmd) if rr_mode >= 1 else cmd)
        self.pxc_startup_status(3)

        if is_startup == "startup":
            sh(f"{basedir}/bin/mysql -uroot -S{workdir}/node1.template/node1_socket.sock -e \"create database if not exists test\" > /dev/null 2>&1")

        if is_startup != "startup":
            self.echoit("Checking 3 node PXC Cluster startup...")
            for x in range(0, 11):
                time.sleep(1)
                cluster_up = 0
                if sh_status(f"{basedir}/bin/mysqladmin -uroot -S{self.socket1} ping > /dev/null 2>&1") == 0:
                    for sock in (self.socket1, self.socket2, self.socket3):
                        out = sh_out(f"{basedir}/bin/mysql -uroot -S{sock} -e\"show global status like 'wsrep_cluster_size'\"")
                        val = self._extract_status_value(out, "wsrep_cluster")
                        if val == "3":
                            cluster_up += 1
                    for sock in (self.socket1, self.socket2, self.socket3):
                        out = sh_out(f"{basedir}/bin/mysql -uroot -S{sock} -e\"show global status like 'wsrep_local_state_comment'\"")
                        val = self._extract_status_value(out, "wsrep_local")
                        if val == "Synced":
                            cluster_up += 1
                if cluster_up == 6:
                    self.isstarted = 1
                    self.echoit("3 Node PXC Cluster started ok. Clients:")
                    mysql_bin = self.mysqld_bin.replace("/mysqld", "/mysql")
                    self.echoit(f"Node #1: {mysql_bin} -uroot -S{self.socket1}")
                    self.echoit(f"Node #2: {mysql_bin} -uroot -S{self.socket2}")
                    self.echoit(f"Node #3: {mysql_bin} -uroot -S{self.socket3}")
                    break

    @staticmethod
    def _extract_status_value(mysql_output, key_substring):
        for line in mysql_output.splitlines():
            collapsed = re.sub(r"[|\t ]+", "\t", line.strip())
            if key_substring in collapsed:
                parts = collapsed.split("\t")
                if len(parts) >= 2:
                    return parts[-1]
        return ""

    def b_encryption_run(self):
        return self.i("ENCRYPTION_RUN") == 1

    def _spawn(self, cmd, out_path=None, env=None):
        """Start a background shell command; returns the child's PID and keeps
        a handle so kill_server() can later do a real, confirmed wait()
        instead of a best-effort existence poll (see kill_server)."""
        if out_path:
            f = open(out_path, "ab")
            proc = subprocess.Popen(["/bin/bash", "-c", cmd], stdout=f, stderr=subprocess.STDOUT, env=env)
        else:
            proc = subprocess.Popen(["/bin/bash", "-c", cmd], env=env)
        self._tracked_procs[proc.pid] = proc
        return proc.pid

