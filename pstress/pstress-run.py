#!/usr/bin/env python3
"""Python port of pstress-run.sh.

SQL File Execution Mode:
This script also supports executing dump and reduced SQL files obtained from a
pstress trial instead of running pstress trials. To enable this mode, set the
following variables in your configuration file:
  EXECUTE_SQL_FILES_MODE=1          # Set to 1 to enable SQL file execution mode (default: 0)
  SQL_FILES_DIR=/path/to/sql/files  # Directory containing SQL files organized by step number (default: $HOME/pstress_sql_files)
  SQL_FILES_STEP_NUM=N              # Step number to execute (required when EXECUTE_SQL_FILES_MODE=1)
  SQL_FILES_NUMBER_OF_TIMES=N       # Number of times to execute the SQL files (default: 1)
  SQL_FILES_SINGLE_THREADED=0       # Set to 1, will execute reduced SQL files sequentially one by one (default: 0)
  SQL_FILES_TIMEOUT=60              # Timeout in seconds for SQL file execution (default: 60)
  SQL_FILES_KILL_AND_RESTART_SERVER=0  # Set to 1 to kill and restart server after SQL_FILES_TIMEOUT seconds post triggering the SQL file/s execution (default: 0)

The SQL files directory structure should be as generated by the replay_test.sh script when run in SQL FILES MODE:
  ${SQL_FILES_DIR}/${SQL_FILES_STEP_NUM}/
    - ts${SQL_FILES_STEP_NUM}.sql (optional). Tablespace creation SQL file.
    - dump_pstress${SQL_FILES_STEP_NUM}.sql (required if SQL_FILES_SINGLE_THREADED=0). Dump file obtained from the prior trial.
    - workaround.sql (optional). Workaround SQL queries, if any, to be executed before the reduced_* SQL files execution.
    - reduced_*.sql (Reduced pstress SQL files of the corresponding step to execute)

Configuration files are real bash (they can reference $SCRIPT_PWD/$RANDOMD/$HOME,
use conditionals, and declare the KMIP_CONFIGS associative array), so this port
loads them by sourcing them with bash and reading back the resulting variables
rather than re-implementing a bash parser.
"""

