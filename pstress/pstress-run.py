    def ctrl_c(self):
        self.echoit("CTRL+C Was pressed. Attempting to terminate running processes...")
        kill_pids = pids_matching(self.randomd)
        if kill_pids:
            self.echoit(f"Terminating the following PID's: {' '.join(str(p) for p in kill_pids)}")
            for pid in kill_pids:
                try:
                    os.kill(pid, 9)
                except OSError:
                    pass
        rundir = self.s("RUNDIR")
        workdir = self.s("WORKDIR")
        trial_dir = f"{rundir}/{self.trial}/"
        if os.path.isdir(trial_dir):
            self.echoit(f"Done. Moving the trial {SCRIPT_NAME} was currently working on to workdir as {workdir}/{self.trial}/...")
            proc = subprocess.run(["mv", trial_dir, f"{workdir}/"], capture_output=True, text=True)
            append_text(f"{workdir}/pstress-run.log", (proc.stdout or "") + (proc.stderr or ""))
        self.echoit(f"Attempting to cleanup the pstress rundir {rundir}...")
        shutil.rmtree(rundir, ignore_errors=True)
        if self.saved == 0 and self.i("SAVE_SQL") == 0:
            self.echoit("There were no coredumps saved, and SAVE_SQL=0, so the workdir can be safely deleted. Doing so...")
            self.workdiractive = False
            shutil.rmtree(workdir, ignore_errors=True)
        else:
            self.echoit(f"The results of this run can be found in the workdir {workdir}...")
        self.echoit(f"Done. Terminating {SCRIPT_NAME} with exit code 2...")
        sys.exit(2)

    # ------------------------------------------------------------------
    # Random option helper (shared by ADD_RANDOM_OPTIONS / ADD_RANDOM_ROCKSDB_OPTIONS / PXC_*)
    # ------------------------------------------------------------------
    @staticmethod
    def random_options(options_infile, max_nr):
        nr_to_add = random.randint(0, 32767) % max_nr + 1
        chosen_names = []
        chosen_options = []
        try:
            with open(options_infile) as fh:
                pool = [l.rstrip("\n") for l in fh if l.strip()]
        except OSError:
            pool = []
        if not pool:
            return ""
        for _ in range(nr_to_add):
            option = random.choice(pool)
            name = option.split("=", 1)[0]
            if name not in chosen_names:
                chosen_names.append(name)
                chosen_options.append(option)
        return " ".join(chosen_options)

