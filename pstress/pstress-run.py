# Field/record separators used to move data out of the bash config-loading
# subprocess without fighting bash's own quoting rules in declare -p output.
_FS = "\x1f"
_RS = "\x1e"


def sh(cmd, **kw):
    """Run a shell command (bash semantics), ignoring the exit code unless asked."""
    kw.setdefault("executable", "/bin/bash")
    return subprocess.run(cmd, shell=True, **kw)


def sh_out(cmd, **kw):
    """Run a shell command and return stdout (stripped), bash semantics."""
    kw.setdefault("executable", "/bin/bash")
    proc = subprocess.run(cmd, shell=True, capture_output=True, text=True, **kw)
    return proc.stdout.strip()


def sh_status(cmd, **kw):
    kw.setdefault("executable", "/bin/bash")
    return subprocess.run(cmd, shell=True, **kw).returncode


def command_exists(name):
    return shutil.which(name) is not None


def read_text(path):
    try:
        return Path(path).read_text()
    except OSError:
        return ""


def write_text(path, content):
    Path(path).write_text(content)


def append_text(path, content):
    with open(path, "a") as fh:
        fh.write(content)


def sed_2i(path, line):
    """Mimic `sed -i "2i TEXT" path`: insert TEXT as the new second line."""
    p = Path(path)
    lines = p.read_text().splitlines(keepends=True)
    if lines and not lines[0].endswith("\n"):
        lines[0] += "\n"
    lines.insert(1, line + "\n")
    p.write_text("".join(lines))


def bash_index(seq, idx):
    """Mimic bash array indexing: an out-of-range index yields ''."""
    return seq[idx] if 0 <= idx < len(seq) else ""


def bash_unreadable(value):
    """Mimic `[ ! -r ${value} ]` (unquoted) from pstress-run.sh.

    When `value` is empty, the unquoted expansion vanishes from the command
    line entirely, degenerating the test to `[ ! -r ]` -- a 2-argument test
    that POSIX evaluates as "negate whether the literal string -r is
    non-empty", i.e. always false. So bash treats an unset/empty variable as
    "readable" (the check is skipped), not as "unreadable". Several
    pstress-run-*.conf files (all PXC/GR ones) rely on exactly this to leave
    OPTIONS_INFILE unset. A naive os.access("", ...) check would say
    "unreadable" and abort where the shell script would not.
    """
    if value == "":
        return False
    return not os.access(value, os.R_OK)


def pids_matching(*substrings, exclude_grep=True):
    """Roughly equivalent to: ps -ef | grep <substrings...> | awk '{print $2}'."""
    try:
        out = subprocess.run(["ps", "-ef"], capture_output=True, text=True).stdout
    except OSError:
        return []
    pids = []
    for line in out.splitlines():
        if all(s in line for s in substrings):
            parts = line.split()
            if len(parts) > 1:
                try:
                    pids.append(int(parts[1]))
                except ValueError:
                    continue
    return pids


def process_ids_matching(pattern):
    return pids_matching(pattern)


def grep_count(pattern, *paths, ignore_case=True):
    files = []
    for path in paths:
        files.extend(glob.glob(path))
    if not files:
        return 0
    count = 0
    flags = re.IGNORECASE if ignore_case else 0
    try:
        rx = re.compile(pattern, flags)
    except re.error:
        rx = re.compile(re.escape(pattern), flags)
    for f in files:
        try:
            with open(f, "r", errors="replace") as fh:
                for l in fh:
                    if rx.search(l):
                        count += 1
        except OSError:
            continue
    return count


def file_contains(path, pattern, ignore_case=True):
    return grep_count(pattern, path, ignore_case=ignore_case) > 0


def normalize_version(version_str):
    """Format version string (thanks to wsrep_sst_xtrabackup-v2)."""
    m = re.match(r"^(\d+)\.(\d+)\.?(\d*)(\.\d*)*$", version_str or "")
    if not m:
        return "000000"
    major = int(m.group(1) or 0)
    minor = int(m.group(2) or 0)
    patch = int(m.group(3) or 0)
    return "%02d%02d%02d" % (major, minor, patch)


def check_for_version(local_version, required_version):
    """Version comparison (thanks to wsrep_sst_xtrabackup-v2). True if local >= required."""
    return normalize_version(local_version) >= normalize_version(required_version)


def load_bash_config(script_pwd, config_path, randomd):
    """Source config_path with bash and return (scalars, arrays) dicts.

    `arrays` maps associative/indexed array names to dict[key] -> value
    (indexed arrays use string indices "0", "1", ...).
    """
    driver = r"""
set -a
SCRIPT_PWD="$1"
RANDOMD="$2"
CONFIG_FILE="$3"
before_vars=$(compgen -v)
source "$CONFIG_FILE"
after_vars=$(compgen -v)
FS=$'\x1f'
RS=$'\x1e'
new_vars=$(comm -13 <(echo "$before_vars" | sort) <(echo "$after_vars" | sort))
for v in $new_vars; do
  case "$v" in
    before_vars|after_vars|new_vars|FS|RS|v|SCRIPT_PWD|RANDOMD|CONFIG_FILE) continue ;;
  esac
  decl=$(declare -p "$v" 2>/dev/null)
  case "$decl" in
    "declare -A"*)
      printf 'ARRAY%s%s%s' "$FS" "$v" "$RS"
      eval "keys=(\"\${!$v[@]}\")"
      for k in "${keys[@]}"; do
        eval "val=\"\${$v[\$k]}\""
        printf 'KV%s%s%s%s%s%s%s' "$FS" "$v" "$FS" "$k" "$FS" "$val" "$RS"
      done
      ;;
    "declare -a"*)
      printf 'LIST%s%s%s' "$FS" "$v" "$RS"
      eval "n=\${#$v[@]}"
      for ((i=0; i<n; i++)); do
        eval "val=\"\${$v[$i]}\""
        printf 'ITEM%s%s%s%s%s' "$FS" "$v" "$FS" "$val" "$RS"
      done
      ;;
    *)
      val="${!v}"
      printf 'VAR%s%s%s%s%s' "$FS" "$v" "$FS" "$val" "$RS"
      ;;
  esac
done
"""
    proc = subprocess.run(
        ["bash", "-c", driver, "bash_config_loader", str(script_pwd), str(randomd), str(config_path)],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise RuntimeError(f"Failed to source configuration file {config_path}")

    scalars = {}
    arrays = {}
    for record in proc.stdout.split(_RS):
        if not record:
            continue
        fields = record.split(_FS)
        kind = fields[0]
        if kind == "VAR" and len(fields) >= 3:
            scalars[fields[1]] = fields[2]
        elif kind == "KV" and len(fields) >= 4:
            arrays.setdefault(fields[1], {})[fields[2]] = fields[3]
        elif kind == "ITEM" and len(fields) >= 3:
            lst = arrays.setdefault(fields[1], {})
            lst[str(len(lst))] = fields[2]
        elif kind in ("ARRAY", "LIST"):
            arrays.setdefault(fields[1], {})
    return scalars, arrays


